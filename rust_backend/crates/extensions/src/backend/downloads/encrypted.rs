//! Experimental host-only MOV/CENC boundary. Never registered by mobile/desktop.
//! The provider cannot enable it, choose a finalizer path, or receive its key back.

use super::*;
use crate::ffmpeg::{PrivateProducer, ProducerTerminal};
use crate::files::{FilePath, FileRegistry};
use std::io::{Seek, SeekFrom};
use std::path::PathBuf;
use std::sync::atomic::{AtomicU8, Ordering};
use zeroize::Zeroizing;

#[cfg(any(target_os = "android", all(target_os = "linux", test)))]
#[allow(dead_code)] // The normal host does not register the experimental capability.
mod private_publication;

const MAX_BYTES: u64 = 512 * 1024 * 1024;

fn supported_quality(manifest: &ExtensionManifest, quality: &str) -> bool {
    manifest.find_quality(quality).is_some_and(|option| {
        crate::manifest::quality_signature(option)
            .is_some_and(|(codec, _, _)| codec == "flac")
            || (manifest.name == "amazon"
                && option.id == "best"
                && option.kind.eq_ignore_ascii_case("lossless")
                && option.label == "FLAC Best Available")
    })
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum PrivateFinalizationError {
    Failed,
    Cancelled,
    ProducerUnconfirmed,
}

/// Host capability, deliberately absent from request JSON and provider APIs.
/// Implementations must not put keys in argv, sessions, logs or persistence.
/// Return is not termination: signal the job separately after a genuine native
/// terminal event. If that event is unknown, retain the job for the late callback.
pub trait PrivateMovFinalizer: Send + Sync {
    fn finalize(&self, job: Arc<PrivateMovJob>) -> Result<(), PrivateFinalizationError>;
}

/// Deliberately has no Debug/Serialize implementation. Paths are generated by
/// the host; only the finalizer receives this object. Secret bytes are zeroized
/// when the last producer/caller reference is released.
pub struct PrivateMovJob {
    input: PathBuf,
    output: PathBuf,
    key: Zeroizing<Vec<u8>>,
    lease: Arc<RequestLease>,
    producer: PrivateProducer,
    terminal: AtomicU8,
}

impl PrivateMovJob {
    pub fn input_path(&self) -> &Path {
        &self.input
    }
    pub fn output_path(&self) -> &Path {
        &self.output
    }
    pub fn key_bytes(&self) -> &[u8] {
        &self.key
    }
    pub fn is_cancelled(&self) -> bool {
        self.lease.is_cancelled_fail_closed()
    }
    pub fn acknowledge_terminal(&self, terminal: ProducerTerminal) {
        let value = match terminal {
            ProducerTerminal::NotStarted => 1,
            ProducerTerminal::Stopped => 2,
        };
        if self
            .terminal
            .compare_exchange(0, value, Ordering::AcqRel, Ordering::Acquire)
            .is_ok()
        {
            self.producer.acknowledge();
        }
    }
}

impl Backend {
    /// Experimental host registration. Enabling the Cargo feature without this
    /// capability leaves the existing encrypted rejection in force.
    pub fn register_private_mov_finalizer(
        &self,
        finalizer: Arc<dyn PrivateMovFinalizer>,
    ) -> Result<(), String> {
        self.check()?;
        let root = self
            .environment()
            .data_directory()
            .join(".host-private-mov");
        std::fs::create_dir_all(&root).map_err(|_| "private staging unavailable")?;
        if !std::fs::symlink_metadata(&root)
            .is_ok_and(|info| info.is_dir() && !info.file_type().is_symlink())
        {
            return Err("private staging unavailable".into());
        }
        self.environment()
            .reserve_private_directory(&root)
            .map_err(|_| "private staging overlaps an extension grant")?;
        self.environment()
            .ffmpeg_commands()
            .enable_typed_producer_lifetime()
            .map_err(|e| e.to_string())?;
        // Readers hold this capability through provider return, so activation
        // cannot split a concurrent legacy selection from its manager call.
        let mut registered = self
            .private_mov_finalizer
            .write()
            .expect("private finalizer lock");
        self.enable_private_downloads();
        *registered = Some(finalizer);
        Ok(())
    }
}

pub(super) fn supports_request(request: &DownloadRequest) -> bool {
    !request.output_dir.is_empty()
        && request.output_path.is_empty()
        && request.output_fd == 0
        && request.output_ext.eq_ignore_ascii_case(".flac")
        && !request.allow_quality_fallback
        && !request.quality.trim().is_empty()
        // This request may already contain provider-enriched free text. Until
        // the original host fields are carried separately, tagging can leak
        // provider secrets even when the descriptor itself is kept private.
        && !request.embed_metadata
        && !request.embed_lyrics
        && !request.embed_replaygain
        && !request.post_processing_enabled
        && !request.requires_container_conversion
}

fn copy_bounded(
    source: &mut impl Read,
    output: &mut impl Write,
    check: &Check<'_>,
) -> Result<(), String> {
    let mut bytes = [0u8; 65536];
    let mut total = 0u64;
    loop {
        check()?;
        let count = source
            .read(&mut bytes)
            .map_err(|_| "private media read failed")?;
        if count == 0 {
            break;
        }
        total = total
            .checked_add(count as u64)
            .ok_or("private media too large")?;
        if total > MAX_BYTES {
            return Err("private media too large".into());
        }
        output
            .write_all(&bytes[..count])
            .map_err(|_| "private media write failed")?;
    }
    if total == 0 {
        return Err("private media is empty".into());
    }
    Ok(())
}

fn validate_flac(file: &mut cap_std::fs::File, check: &Check<'_>) -> Result<(), String> {
    file.seek(SeekFrom::Start(0))
        .map_err(|_| "private media seek failed")?;
    let mut reader = claxon::FlacReader::new(std::io::BufReader::new(file))
        .map_err(|_| "private media decode failed")?;
    let info = reader.streaminfo();
    if info.sample_rate == 0 || info.channels == 0 || info.bits_per_sample == 0 {
        return Err("private media decode failed".into());
    }
    let expected = info
        .samples
        .and_then(|n| n.checked_mul(u64::from(info.channels)));
    let maximum = u64::from(info.sample_rate) * u64::from(info.channels) * 6 * 3600;
    let mut count = 0u64;
    for sample in reader.samples() {
        if count.is_multiple_of(4096) {
            check()?;
        }
        sample.map_err(|_| "private media decode failed")?;
        count += 1;
        if count > maximum {
            return Err("private media decode limit exceeded".into());
        }
    }
    if count == 0 || expected.is_some_and(|n| n != count) {
        return Err("private media is incomplete".into());
    }
    check()
}

#[allow(clippy::too_many_arguments)]
pub(super) fn finalize_local(
    backend: &Backend,
    finalizer: Arc<dyn PrivateMovFinalizer>,
    request: &DownloadRequest,
    manifest: &ExtensionManifest,
    decryption: crate::manager::PrivateDecryption,
    input: &FilePath,
    destination: &FilePath,
    final_path: &str,
    lease: Arc<RequestLease>,
    check: &Check<'_>,
) -> Result<DownloadOutcome, String> {
    let failed = || {
        DownloadOutcome::Final(failure(
            &manifest.name,
            "private encrypted finalization failed validation; no output was published",
            "quality_unavailable",
            0,
        ))
    };
    if !supports_request(request) {
        return Ok(failed());
    }
    // Exact tiers require a complete signature. Amazon's declared best FLAC
    // tier asks the provider for its best available option; its actual depth
    // and rate are measured from the fully decoded output below.
    if !supported_quality(manifest, &request.quality) {
        return Ok(failed());
    }
    let key = match decryption.into_mov_key() {
        Ok(key) => key,
        Err(()) => return Ok(failed()),
    };
    // This root is outside every extension's data root and is NEVER granted to
    // the provider. Do not use its supplied output_path as plaintext staging.
    let environment = backend.environment();
    let root = environment.data_directory().join(".host-private-mov");
    match std::fs::create_dir(&root) {
        Ok(()) => (),
        Err(error) if error.kind() == std::io::ErrorKind::AlreadyExists => (),
        Err(_) => return Ok(failed()),
    }
    if !std::fs::symlink_metadata(&root)
        .is_ok_and(|info| info.is_dir() && !info.file_type().is_symlink())
    {
        return Ok(failed());
    }
    #[cfg(unix)]
    {
        use std::os::unix::fs::PermissionsExt;
        std::fs::set_permissions(&root, std::fs::Permissions::from_mode(0o700))
            .map_err(|_| "private staging unavailable")?;
    }
    let directory = tempfile::Builder::new()
        .prefix("attempt-")
        .tempdir_in(root)
        .map_err(|_| "private staging unavailable")?;
    let private = environment
        .ffmpeg_commands()
        .protect_download_staging(&manifest.name, directory)
        .map_err(|_| "private staging unavailable")?;
    let private_files = Arc::new(FileRegistry::default())
        .extension(private.path())
        .map_err(|_| "private staging unavailable")?;
    let encrypted = private.path().join("input.mp4");
    let plain = private.path().join("output.flac");
    let mut snapshot = std::fs::OpenOptions::new()
        .write(true)
        .create_new(true)
        .open(&encrypted)
        .map_err(|_| "private staging unavailable")?;
    let mut source = input
        .open_native_read()
        .map_err(|_| "private source unavailable")?;
    copy_bounded(&mut source, &mut snapshot, check)?;
    snapshot
        .sync_all()
        .map_err(|_| "private staging sync failed")?;
    drop(snapshot);
    drop(source);
    check()?;
    let producer = private
        .begin_private_producer()
        .map_err(|_| "private producer unavailable")?;
    let job = Arc::new(PrivateMovJob {
        input: encrypted,
        output: plain,
        key,
        lease: Arc::clone(&lease),
        producer,
        terminal: AtomicU8::new(0),
    });
    let outcome = finalizer.finalize(Arc::clone(&job));
    check()?;
    if outcome.is_err() || job.terminal.load(Ordering::Acquire) != 2 {
        return Ok(failed());
    }
    // Reopen only the fixed host-owned filename; reject symlinks and directories.
    let output = private_files
        .resolve("output.flac")
        .map_err(|_| "private output unavailable")?;
    let mut clear = match output.open_native_read() {
        Ok(file) => file,
        Err(_) => return Ok(failed()),
    };
    let mut staged = destination
        .stage()
        .map_err(|_| "publication staging unavailable")?;
    copy_bounded(&mut clear, &mut staged.file, check)?;
    // Decode the exact independently owned destination staging, then probe it.
    // A header-only file, corrupt frames or truncated body cannot pass.
    if validate_flac(&mut staged.file, check).is_err() {
        check()?;
        return Ok(failed());
    }
    let mut measured = json!({});
    probe_open_file(&mut staged.file, final_path, &mut measured, false, check)?;
    if text(&measured, "audio_codec") != "flac"
        || !strict_codec_matches(request, manifest, &measured)
    {
        return Ok(failed());
    }
    let mut response = success(request, &measured, final_path, false, manifest, check)?;
    check()?;
    if staged.publish_new_with_lease(&lease).is_err() {
        check()?;
        return Ok(failed());
    }
    response["private_finalization_validated"] = true.into();
    response["skip_metadata_enrichment"] = true.into();
    response = finish_committed_download(response, |response| {
        if text(response, "isrc").trim().is_empty() {
            return Ok(());
        }
        environment
            .invalidate_isrc_cache(&request.output_dir)
            .map_err(|error| error.to_string())?;
        environment
            .add_to_isrc_index(
                destination
                    .absolute
                    .parent()
                    .unwrap_or(Path::new("."))
                    .to_string_lossy()
                    .as_ref(),
                text(response, "isrc").trim(),
                final_path,
                &|| Ok(()),
            )
            .map_err(|error| error.to_string())
    });
    Ok(DownloadOutcome::Final(response))
}

