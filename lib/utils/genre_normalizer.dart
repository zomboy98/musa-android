final RegExp _alnum = RegExp(r'[a-z0-9]');
final RegExp _singerSongwriter = RegExp(
  r'singer\s*/\s*songwriter',
  caseSensitive: false,
);
final RegExp _separators = RegExp(r'\s*(?:;|/|,|\||\n)\s*');

String genreKey(String value) {
  const from = 'áàâäãéèêëíìîïóòôöõúùûüñç';
  const to = 'aaaaaeeeeiiiiooooouuuunc';
  final buffer = StringBuffer();
  final lower = value.toLowerCase();
  for (final unit in lower.runes) {
    final char = String.fromCharCode(unit);
    final index = from.indexOf(char);
    if (index >= 0) {
      buffer.write(to[index]);
    } else if (char == '&') {
      buffer.write('&');
    } else if (_alnum.hasMatch(char)) {
      buffer.write(char);
    } else {
      buffer.write(' ');
    }
  }
  var key = buffer.toString().replaceAll(RegExp(r'\s+'), ' ').trim();
  if (key == 'r & b' || key == 'r&b') key = 'r&b';
  return key;
}

String _capitalized(String value) {
  final trimmed = value.trim();
  if (trimmed.isEmpty) return trimmed;
  return trimmed[0].toUpperCase() + trimmed.substring(1);
}

String? _containsRule(String key) {
  if (key.contains('corrid')) {
    if (key.contains('tumbad')) return 'Corridos tumbados';
    if (key.contains('belic')) return 'Corridos bélicos';
    return 'Corridos';
  }
  if (key.contains('reggaeton') || key.contains('reguet')) return 'Reguetón';
  if (key.contains('rock') &&
      (key.contains('espanol') ||
          key.contains('spanish') ||
          key.contains('latin'))) {
    return 'Rock en español';
  }
  if (key.contains('k pop') || key.contains('kpop')) return 'K-pop';
  if (key.contains('sierren')) return 'Sierreño';
  if (key.contains('norten')) return 'Norteño';
  if (key.contains('regional') && key.contains('mexic')) {
    return 'Regional mexicano';
  }
  if (key.contains('mariachi') || key.contains('ranchera')) {
    return 'Música tradicional mexicana';
  }
  return null;
}

List<String> _splitGenres(Iterable<String?> raw) {
  final parts = <String>[];
  for (final value in raw) {
    if (value == null) continue;
    final protectedValue = value.replaceAll(
      _singerSongwriter,
      'singer songwriter',
    );
    for (final part in protectedValue.split(_separators)) {
      final trimmed = part.trim();
      if (trimmed.isNotEmpty) parts.add(trimmed);
    }
  }
  return parts;
}

/// Turns the genres a provider reports into Spanish display names.
///
/// [raw] may hold several genres in one string, separated by `;`, `/`, `,` or
/// `|`. Aliases and English names map to one Spanish name, duplicates are
/// removed and at most [maxGenres] are returned in their original order.
/// Genres without an entry keep their text with the first letter capitalised.
List<String> normalizeGenres(Iterable<String?> raw, {int maxGenres = 3}) {
  final parts = _splitGenres(raw);
  if (parts.isEmpty || maxGenres <= 0) return const [];
  final keys = [for (final part in parts) genreKey(part)];
  final result = <String>[];
  final seen = <String>{};
  for (var i = 0; i < parts.length; i++) {
    final key = keys[i];
    if (key.isEmpty) continue;
    final name = _aliases[key] ?? _containsRule(key) ?? _capitalized(parts[i]);
    if (seen.add(genreKey(name))) result.add(name);
  }
  return result.length <= maxGenres ? result : result.sublist(0, maxGenres);
}

/// The genres of [raw] ready to show on one line, joined with " · ", or null
/// when there is nothing to show.
String? formatGenres(Iterable<String?> raw, {int maxGenres = 2}) {
  final genres = normalizeGenres(raw, maxGenres: maxGenres);
  return genres.isEmpty ? null : genres.join(' · ');
}
